-- TAJO TAP V6 — Smart Page + venda vinculada por e-mail + acesso de cliente
-- Execute APÓS 001..007. Não apaga dados existentes.

begin;

-- ---------------------------------------------------------------------------
-- Venda: guarda o e-mail informado pelo vendedor para vinculação do cliente.
-- ---------------------------------------------------------------------------
alter table public.tap_sales add column if not exists customer_email text;

create index if not exists tap_sales_customer_email_idx
  on public.tap_sales(lower(customer_email));

-- ---------------------------------------------------------------------------
-- Convites de acesso: o e-mail é apenas a referência de vinculação.
-- O vínculo real continua sendo auth.users.id em tap_client_members.
-- ---------------------------------------------------------------------------
create table if not exists public.tap_client_access_invites (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.tap_clients(id) on delete cascade,
  plate_id uuid references public.tap_plates(id) on delete cascade,
  seller_id uuid references public.tap_sellers(id) on delete set null,
  email text not null,
  status text not null default 'pending' check (status in ('pending','claimed','revoked')),
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  claimed_by uuid references auth.users(id) on delete set null,
  unique (client_id, email)
);

create index if not exists tap_client_access_invites_email_idx
  on public.tap_client_access_invites(lower(email), status, created_at desc);

-- ---------------------------------------------------------------------------
-- Smart Pages: uma empresa pode ter várias páginas; uma plaquinha pode ter
-- no máximo uma Smart Page diretamente vinculada.
-- ---------------------------------------------------------------------------
create table if not exists public.tap_smart_pages (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.tap_clients(id) on delete cascade,
  plate_id uuid unique references public.tap_plates(id) on delete set null,
  created_by_seller_id uuid references public.tap_sellers(id) on delete set null,
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{2,62}$'),
  business_name text not null check (char_length(business_name) between 2 and 120),
  subtitle text,
  bio text,
  logo_url text,
  cover_url text,
  primary_color text not null default '#45E600',
  background_color text not null default '#0B0D0E',
  text_color text not null default '#F4F7F2',
  button_style text not null default 'rounded' check (button_style in ('rounded','pill','square')),
  whatsapp text,
  phone text,
  public_email text,
  instagram text,
  tiktok text,
  website_url text,
  maps_url text,
  google_review_url text,
  pix_key text,
  wifi_name text,
  wifi_password text,
  address text,
  opening_hours text,
  services jsonb not null default '[]'::jsonb,
  custom_links jsonb not null default '[]'::jsonb,
  seller_edit_allowed boolean not null default true,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists tap_smart_pages_updated_at on public.tap_smart_pages;
create trigger tap_smart_pages_updated_at
before update on public.tap_smart_pages
for each row execute function public.tap_set_updated_at();

create index if not exists tap_smart_pages_client_idx on public.tap_smart_pages(client_id, created_at desc);
create index if not exists tap_smart_pages_seller_idx on public.tap_smart_pages(created_by_seller_id, created_at desc);
create index if not exists tap_smart_pages_slug_idx on public.tap_smart_pages(slug);

-- ---------------------------------------------------------------------------
-- Analytics de Smart Page. Não armazena IP, fingerprint ou dado sensível.
-- ---------------------------------------------------------------------------
create table if not exists public.tap_smart_page_events (
  id bigint generated by default as identity primary key,
  smart_page_id uuid not null references public.tap_smart_pages(id) on delete cascade,
  event_type text not null check (event_type in ('view','click')),
  action_key text,
  action_label text,
  occurred_at timestamptz not null default now()
);

create index if not exists tap_smart_page_events_page_time_idx
  on public.tap_smart_page_events(smart_page_id, occurred_at desc);
create index if not exists tap_smart_page_events_action_idx
  on public.tap_smart_page_events(smart_page_id, action_key, occurred_at desc);

-- ---------------------------------------------------------------------------
-- Segurança: navegador não fala diretamente com essas tabelas.
-- O backend TAJO aplica autorização por admin/vendedor/cliente.
-- ---------------------------------------------------------------------------
alter table public.tap_client_access_invites enable row level security;
alter table public.tap_smart_pages enable row level security;
alter table public.tap_smart_page_events enable row level security;

revoke all on public.tap_client_access_invites from anon, authenticated;
revoke all on public.tap_smart_pages from anon, authenticated;
revoke all on public.tap_smart_page_events from anon, authenticated;

grant all on public.tap_client_access_invites to service_role;
grant all on public.tap_smart_pages to service_role;
grant all on public.tap_smart_page_events to service_role;

commit;

-- Verificação rápida
select
  to_regclass('public.tap_smart_pages') as smart_pages,
  to_regclass('public.tap_smart_page_events') as smart_events,
  to_regclass('public.tap_client_access_invites') as access_invites,
  (select count(*) from information_schema.columns
   where table_schema='public' and table_name='tap_sales' and column_name='customer_email') as sale_email_column;
